def render_glossary(
    article: Mapping[str, object],
    terms: list[Mapping[str, object]],
    *,
    english_slug: str | None = None,
) -> str:
    metadata = _metadata(article)
    title = _required_text(metadata, "title", "glossary.metadata")
    description = _required_text(metadata, "summary", "glossary.metadata")
    web_slug = _web_slug(article)
    canonical = f"{SITE_URL}/guides/{web_slug}/"
    term_by_slug = {
        _required_text(term, "slug", "glossary term"): term for term in terms
    }
    grouped_terms: dict[str, list[Mapping[str, object]]] = {}
    for term in terms:
        label = _required_text(term, "label", "glossary term")
        letter = _alphabetical_key(label)[0].upper()
        grouped_terms.setdefault(letter, []).append(term)

    letter_links = "\n".join(
        f'          <li><a href="#lettre-{escape(letter.lower(), quote=True)}">'
        f"{escape(letter)}</a></li>"
        for letter in grouped_terms
    )
