class GuideBuildError(RuntimeError):
    """Raised when public guide pages cannot be generated safely."""


def load_corpus(path: Path) -> Mapping[str, object]:
    try:
        payload = json.loads(path.read_text(encoding="utf-8"))
    except OSError as error:
        raise GuideBuildError(f"cannot read Academy corpus {path}: {error}") from error
    except json.JSONDecodeError as error:
        raise GuideBuildError(
            f"cannot parse Academy corpus {path}: {error.msg}"
        ) from error

    return _mapping(payload, "Academy corpus")


def load_english_guides(path: Path) -> Mapping[str, object]:
    try:
        payload = json.loads(path.read_text(encoding="utf-8"))
    except OSError as error:
        raise GuideBuildError(f"cannot read English guides {path}: {error}") from error
    except json.JSONDecodeError as error:
        raise GuideBuildError(
            f"cannot parse English guides {path}: {error.msg}"
        ) from error

    return _mapping(payload, "English guides")


def public_articles(corpus: Mapping[str, object]) -> list[Mapping[str, object]]:
    raw_articles = corpus.get("articles")
    if not isinstance(raw_articles, list):
        raise GuideBuildError('Academy corpus field "articles" must be an array')

    articles: list[Mapping[str, object]] = []
    web_slugs: set[str] = set()
    for index, raw_article in enumerate(raw_articles):
        article = _mapping(raw_article, f"articles.{index}")
        metadata = _mapping(article.get("metadata"), f"articles.{index}.metadata")
        if metadata.get("category") == "glossary":
            continue
        raw_web_publication = metadata.get("webPublication")
        if raw_web_publication is None:
            continue

        web_publication = _mapping(
            raw_web_publication, f"articles.{index}.metadata.webPublication"
        )
        if web_publication.get("status") != "published":
            continue

        review = _mapping(metadata.get("review"), f"articles.{index}.metadata.review")
        if metadata.get("status") != "published":
            raise GuideBuildError(
                f"articles.{index}: public guide requires Academy status published"
            )
        if review.get("confidenceLevel") != "validated":
            raise GuideBuildError(
                f"articles.{index}: public guide requires validated review confidence"
            )

        web_slug = _required_text(
            web_publication,
            "slug",
            f"articles.{index}.metadata.webPublication",
        )
        if web_slug in web_slugs:
            raise GuideBuildError(f'duplicate public guide slug "{web_slug}"')
        web_slugs.add(web_slug)
        articles.append(article)

    return sorted(articles, key=lambda article: _web_slug(article))


def public_glossary(
    corpus: Mapping[str, object],
) -> tuple[Mapping[str, object], list[Mapping[str, object]]] | None:
    raw_articles = corpus.get("articles")
    if not isinstance(raw_articles, list):
        raise GuideBuildError('Academy corpus field "articles" must be an array')

    glossary_article: Mapping[str, object] | None = None
    for index, raw_article in enumerate(raw_articles):
        article = _mapping(raw_article, f"articles.{index}")
        if article.get("slug") == GLOSSARY_ACADEMY_SLUG:
            glossary_article = article
            break

    if glossary_article is None:
        return None

    metadata = _metadata(glossary_article)
    raw_web_publication = metadata.get("webPublication")
    if raw_web_publication is None:
        return None

    web_publication = _mapping(raw_web_publication, "glossary.metadata.webPublication")
    if web_publication.get("status") != "published":
        return None
    if metadata.get("status") != "published":
        raise GuideBuildError("glossary: public page requires Academy status published")
    review = _mapping(metadata.get("review"), "glossary.metadata.review")
    if review.get("confidenceLevel") != "validated":
        raise GuideBuildError(
            "glossary: public page requires validated review confidence"
        )

    raw_terms = corpus.get("glossaryTerms")
    if not isinstance(raw_terms, list) or not raw_terms:
        raise GuideBuildError(
            "glossary: public page requires a non-empty glossaryTerms array"
        )

    terms = [
        _mapping(raw_term, f"glossaryTerms.{index}")
        for index, raw_term in enumerate(raw_terms)
    ]
    term_slugs: set[str] = set()
    for index, term in enumerate(terms):
        slug = _required_text(term, "slug", f"glossaryTerms.{index}")
        if slug in term_slugs:
            raise GuideBuildError(f'duplicate public glossary term slug "{slug}"')
        term_slugs.add(slug)
        _required_text(term, "label", f"glossaryTerms.{index}")
        _required_text(term, "shortDefinition", f"glossaryTerms.{index}")
        _required_text(term, "detailedDefinition", f"glossaryTerms.{index}")
        _text_list(term, "aliases")
        _text_list(term, "relatedTerms")
        _mapping_list(term, "sources")

    for term in terms:
        for related_slug in _text_list(term, "relatedTerms"):
            if related_slug not in term_slugs:
                raise GuideBuildError(
                    f'glossary term "{term["slug"]}" references unknown term '
                    f'"{related_slug}"'
                )

    return glossary_article, sorted(
        terms,
        key=lambda term: _alphabetical_key(
            _required_text(term, "label", "glossary term")
        ),
    )


def expected_files(
    corpus: Mapping[str, object],
    english_payload: Mapping[str, object] | None = None,
) -> dict[Path, str]:
    articles = public_articles(corpus)
    glossary = public_glossary(corpus)
    if not articles and glossary is None:
        return {}

    english_guides = _english_guides(english_payload) if english_payload else []
    english_by_academy_slug: dict[str, Mapping[str, object]] = {}
    for guide in english_guides:
        _validate_english_guide(guide)
        academy_slug = _optional_academy_slug(guide, "English guide")
        if academy_slug is None:
            continue
        if academy_slug in english_by_academy_slug:
            raise GuideBuildError(
                f'duplicate English guide Academy slug "{academy_slug}"'
            )
        english_by_academy_slug[academy_slug] = guide

    english_glossary = _english_glossary(english_payload) if english_payload else None
    if english_glossary is not None:
        _validate_english_glossary(english_glossary)

    article_by_academy_slug = {
        _required_text(article, "slug", "article"): article for article in articles
    }
    glossary_slugs = (
        {_required_text(term, "slug", "glossary term") for term in glossary[1]}
        if glossary is not None
        else set()
    )
    glossary_web_slug = _web_slug(glossary[0]) if glossary is not None else None
    article_web_slugs = {_web_slug(article) for article in articles}
    if glossary_web_slug in article_web_slugs:
        raise GuideBuildError(f'duplicate public guide slug "{glossary_web_slug}"')

    has_english_content = bool(english_guides or english_glossary)
    files = {
        Path("index.html"): render_hub(
            articles,
            glossary,
            english_alternate=has_english_content,
        )
    }
    for article in articles:
        academy_slug = _required_text(article, "slug", "article")
        english_guide = english_by_academy_slug.get(academy_slug)
        files[Path(_web_slug(article)) / "index.html"] = render_article(
            article,
            article_by_academy_slug,
            glossary_web_slug,
            glossary_slugs,
            english_slug=(
                _required_text(english_guide, "slug", "English guide")
                if english_guide is not None
                else None
            ),
        )
    if glossary is not None:
        english_glossary_slug = None
        if (
            english_glossary is not None
            and _optional_academy_slug(english_glossary, "English glossary")
            == GLOSSARY_ACADEMY_SLUG
        ):
            english_glossary_slug = _required_text(
                english_glossary, "slug", "English glossary"
            )
        files[Path(glossary_web_slug) / "index.html"] = render_glossary(
            *glossary,
            english_slug=english_glossary_slug,
        )
    return files


def expected_english_files(
    corpus: Mapping[str, object],
    english_payload: Mapping[str, object],
) -> dict[Path, str]:
    guides = _english_guides(english_payload)
    glossary = _english_glossary(english_payload)
    walkthrough = _english_walkthrough(english_payload)
    if not guides and glossary is None:
        return {}

    _validate_english_walkthrough(walkthrough)

    french_articles = {
        _required_text(article, "slug", "article"): article
        for article in public_articles(corpus)
    }
    french_glossary = public_glossary(corpus)
    validated: list[tuple[Mapping[str, object], Mapping[str, object] | None]] = []
    slugs: set[str] = set()
    academy_slugs: set[str] = set()
    for guide in guides:
        _validate_english_guide(guide)
        slug = _required_text(guide, "slug", "English guide")
        if slug in slugs:
            raise GuideBuildError(f'duplicate English content slug "{slug}"')
        slugs.add(slug)

        academy_slug = _optional_academy_slug(guide, "English guide")
        source_article = None
        if academy_slug is not None:
            if academy_slug in academy_slugs:
                raise GuideBuildError(
                    f'duplicate English guide Academy slug "{academy_slug}"'
                )
            academy_slugs.add(academy_slug)
            source_article = french_articles.get(academy_slug)
            if source_article is None:
                raise GuideBuildError(
                    f'English guide references unpublished Academy article "{academy_slug}"'
                )
        validated.append((guide, source_article))

    if glossary is not None:
        _validate_english_glossary(glossary)
        glossary_slug = _required_text(glossary, "slug", "English glossary")
        if glossary_slug in slugs:
            raise GuideBuildError(f'duplicate English content slug "{glossary_slug}"')
        slugs.add(glossary_slug)
        academy_slug = _optional_academy_slug(glossary, "English glossary")
        if academy_slug is not None:
            if academy_slug != GLOSSARY_ACADEMY_SLUG or french_glossary is None:
                raise GuideBuildError(
                    f'English glossary references unpublished Academy article "{academy_slug}"'
                )
            glossary_source = french_glossary[0]
        else:
            glossary_source = None
    else:
        glossary_source = None

    guide_by_slug = {
        _required_text(guide, "slug", "English guide"): guide for guide, _ in validated
    }
    glossary_terms = _mapping_list(glossary, "terms") if glossary is not None else []
    glossary_term_slugs = {
        _required_text(term, "slug", "English glossary term") for term in glossary_terms
    }
    glossary_slug = (
        _required_text(glossary, "slug", "English glossary")
        if glossary is not None
        else None
    )

    files = {
        Path("index.html"): render_english_hub(
            [guide for guide, _ in validated], glossary, walkthrough
        )
    }
    for guide, source_article in validated:
        slug = _required_text(guide, "slug", "English guide")
        files[Path(slug) / "index.html"] = render_english_article(
            guide,
            source_article,
            guide_by_slug,
            glossary_slug,
            glossary_term_slugs,
        )
    if glossary is not None:
        files[Path(glossary_slug) / "index.html"] = render_english_glossary(
            glossary, glossary_source
        )
    return files


def render_hub(
    articles: list[Mapping[str, object]],
    glossary: tuple[Mapping[str, object], list[Mapping[str, object]]] | None = None,
    *,
    english_alternate: bool = False,
) -> str:
    title = "Guides du brassage amateur | Brasse-Bouillon"
    description = (
        "Comprenez les ingrédients, les IBU et les techniques de brassage avec "
        "des guides pratiques, sourcés et pensés pour les brasseurs amateurs."
    )
    canonical = f"{SITE_URL}/guides/"
    cards = [_render_guide_card(article) for article in articles]
    if glossary is not None:
        cards.append(_render_glossary_card(glossary[0], len(glossary[1])))
    breadcrumb = _breadcrumb_schema(
        [("Accueil", f"{SITE_URL}/"), ("Guides", canonical)]
    )
    collection_schema = _json_ld(
        {
            "@context": "https://schema.org",
            "@type": "CollectionPage",
            "name": "Guides du brassage amateur",
            "description": description,
            "url": canonical,
            "inLanguage": "fr-FR",
            "isPartOf": {"@type": "WebSite", "url": f"{SITE_URL}/"},
        }
    )
    main = f"""
    <main id="mainContent" class="guide-shell guide-hub">
      {_visible_breadcrumb([("Accueil", "/"), ("Guides", None)])}
      <header class="guide-hero">
        <p class="guide-eyebrow">Académie Brasse-Bouillon</p>
        <h1>Guides du brassage amateur</h1>
        <p>{escape(description)}</p>
      </header>
      <section class="guide-grid" aria-label="Guides disponibles">
{"\n".join(cards)}
      </section>
    </main>"""
    return _document(
        title,
        description,
        canonical,
        main,
        [breadcrumb, collection_schema],
        og_type="website",
        guides_current=True,
        english_canonical=(f"{SITE_URL}/en/guides/" if english_alternate else None),
    )


def render_article(
    article: Mapping[str, object],
    article_by_academy_slug: Mapping[str, Mapping[str, object]],
    glossary_web_slug: str | None = None,
    glossary_slugs: set[str] | None = None,
    *,
    english_slug: str | None = None,
) -> str:
    metadata = _metadata(article)
    title = _required_text(metadata, "title", "article.metadata")
    description = _required_text(metadata, "summary", "article.metadata")
    web_slug = _web_slug(article)
    canonical = f"{SITE_URL}/guides/{web_slug}/"
    updated_at = _required_text(metadata, "updatedAt", "article.metadata")
    read_time = metadata.get("estimatedReadTimeMinutes")
    if not isinstance(read_time, int) or read_time <= 0:
        raise GuideBuildError(
            "article.metadata.estimatedReadTimeMinutes must be positive"
        )

    body = _mapping(article.get("body"), "article.body")
    raw_sections = body.get("sections")
    if not isinstance(raw_sections, list) or not raw_sections:
        raise GuideBuildError("article.body.sections must be a non-empty array")
    sections = [
        _mapping(section, f"article.body.sections.{index}")
        for index, section in enumerate(raw_sections)
    ]

    toc_items = "\n".join(
        f'          <li><a href="#{escape(_required_text(section, "id", "section"), quote=True)}">'
        f"{escape(_required_text(section, 'title', 'section'))}</a></li>"
        for section in sections
    )
    rendered_sections = "\n".join(
        _render_section(
            section,
            article_by_academy_slug,
            glossary_web_slug,
            glossary_slugs or set(),
        )
        for section in sections
    )
    learning_objectives = _text_list(metadata, "learningObjectives")
    objective_items = "\n".join(
        f"          <li>{escape(objective)}</li>" for objective in learning_objectives
    )
    sources = _mapping_list(metadata, "sources")
    source_items = "\n".join(_render_source(source) for source in sources)
    breadcrumb_items = [
        ("Accueil", f"{SITE_URL}/"),
        ("Guides", f"{SITE_URL}/guides/"),
        (title, canonical),
    ]
    schemas = [
        _breadcrumb_schema(breadcrumb_items),
        _article_schema(title, description, canonical, updated_at),
    ]
    main = f"""
    <main id="mainContent" class="guide-shell">
      {_visible_breadcrumb([("Accueil", "/"), ("Guides", "/guides/"), (title, None)])}
      <article class="guide-article">
        <header class="guide-hero">
          <p class="guide-eyebrow">Guide pratique · Niveau débutant</p>
          <h1>{escape(title)}</h1>
          <p class="guide-lead">{escape(description)}</p>
          <p class="guide-meta">
            Mis à jour le <time datetime="{escape(updated_at, quote=True)}">{escape(updated_at)}</time>
            · {read_time} min de lecture
          </p>
        </header>
        <section class="guide-objectives" aria-labelledby="objectivesTitle">
          <h2 id="objectivesTitle">Ce que tu vas comprendre</h2>
          <ul>
{objective_items}
          </ul>
        </section>
        <nav class="guide-toc" aria-labelledby="tocTitle">
          <h2 id="tocTitle">Dans ce guide</h2>
          <ol>
{toc_items}
          </ol>
        </nav>
{rendered_sections}
        <section class="guide-sources" aria-labelledby="sourcesTitle">
          <h2 id="sourcesTitle">Sources</h2>
          <ol>
{source_items}
          </ol>
        </section>
      </article>
    </main>"""
    return _document(
        title,
        description,
        canonical,
        main,
        schemas,
        og_type="article",
        guides_current=False,
        english_canonical=(
            f"{SITE_URL}/en/guides/{english_slug}/"
            if english_slug is not None
            else None
        ),
    )


